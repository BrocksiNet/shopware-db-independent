#!/usr/bin/env python3
"""Translate the schema of an installed Shopware MariaDB into PostgreSQL 18 DDL.

Reads information_schema through `podman exec <container> mariadb ...` (read-only SELECTs).
Python 3 standard library only.

Usage:
  mysql-to-pg-ddl.py [--container instance-database-1] [--db shopware]
                     [--schema scratch_schema_agent] [--ci all|none] > generated-pg-schema.sql

Design decisions (see findings.md):
  * BINARY(16)                         -> uuid (every BINARY(16) column in the install is a uuid, see findings.md)
  * TINYINT(1) [unsigned]              -> boolean
  * DATETIME(n)/TIMESTAMP(n)           -> timestamp(n) (without time zone, values are UTC)
  * LONGTEXT with CHECK(JSON_VALID())  -> jsonb (the CHECK is dropped, the type enforces it)
  * LONGBLOB/MEDIUMBLOB                -> bytea
  * LONGTEXT holding PHP serialize()   -> bytea (explicit list, SERIALIZED_TEXT_COLS)
  * unsigned INT -> bigint, unsigned BIGINT -> bigint (values > 2^63-1 not representable)
  * utf8mb4_unicode_ci string columns  -> nondeterministic ICU collation "ci" (case + accent insensitive)
  * generated columns                  -> GENERATED ALWAYS AS (...) STORED|VIRTUAL (PG18), expression rewritten for jsonb
  * AUTO_INCREMENT                     -> GENERATED BY DEFAULT AS IDENTITY
  * ON UPDATE CURRENT_TIMESTAMP        -> BEFORE UPDATE trigger
  * index names are made schema-unique by prefixing the table name (PG index names are per schema, MySQL per table)
Order of output: schema/collation, tables (columns + PK + UNIQUE/CHECK), indexes, foreign keys, triggers.
"""
import argparse
import hashlib
import re
import subprocess
import sys
from collections import defaultdict

LIVE_VERSION_UUID = '0fa91ce3-e96a-4bc2-be4b-d9ce752c3425'  # Defaults::LIVE_VERSION


def q(ident):
    return '"' + ident.replace('"', '""') + '"'


def lit(value):
    return "'" + value.replace("'", "''") + "'"


class Db:
    def __init__(self, container, database):
        self.container, self.database = container, database

    def rows(self, sql):
        cmd = ['podman', 'exec', self.container, 'mariadb', '-uroot', '-proot', self.database,
               '--default-character-set=utf8mb4', '-N', '-B', '-r', '-e', sql]
        out = subprocess.run(cmd, check=True, capture_output=True).stdout.decode('utf-8')
        return [line.split('\t') for line in out.split('\n') if line != '']


def mysql_unquote(default):
    """information_schema.column_default holds an SQL literal; return python string or None."""
    if len(default) >= 2 and default[0] == "'" and default[-1] == "'":
        body = default[1:-1].replace("''", "'")
        return body.replace('\\\\', '\\')
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--container', default='instance-database-1')
    ap.add_argument('--db', default='shopware')
    ap.add_argument('--schema', default='scratch_schema_agent')
    ap.add_argument('--ci', default='all', choices=['all', 'none'],
                    help='all: nondeterministic CI collation on every utf8mb4_unicode_ci string column')
    args = ap.parse_args()
    db = Db(args.container, args.db)
    S = lit(args.db)
    warnings = []

    cols = db.rows(
        "select table_name,column_name,column_type,data_type,is_nullable,ifnull(column_default,'<<NULL>>'),extra,"
        "ifnull(generation_expression,''),ifnull(collation_name,'') from information_schema.columns "
        "where table_schema=%s order by table_name,ordinal_position" % S)
    stats = db.rows(
        "select table_name,index_name,non_unique,seq_in_index,column_name,ifnull(sub_part,'') "
        "from information_schema.statistics where table_schema=%s order by table_name,index_name,seq_in_index" % S)
    fkcols = db.rows(
        "select k.table_name,k.constraint_name,k.column_name,k.referenced_table_name,k.referenced_column_name,"
        "r.delete_rule,r.update_rule from information_schema.key_column_usage k join "
        "information_schema.referential_constraints r on r.constraint_schema=k.table_schema and "
        "r.constraint_name=k.constraint_name and r.table_name=k.table_name "
        "where k.table_schema=%s and k.referenced_table_name is not null "
        "order by k.table_name,k.constraint_name,k.ordinal_position" % S)
    checks = db.rows(
        "select table_name,constraint_name,check_clause from information_schema.check_constraints "
        "where constraint_schema=%s order by table_name,constraint_name" % S)
    tables = [r[0] for r in db.rows(
        "select table_name from information_schema.tables where table_schema=%s and table_type='BASE TABLE' "
        "order by 1" % S)]

    # --- JSON columns: longtext-like columns that carry CHECK (json_valid(`col`)) ---
    json_cols = set()
    other_checks = []
    for t, n, clause in checks:
        m = re.search(r'json_valid\(`([^`]+)`\)', clause, re.I)
        if m:
            json_cols.add((t, m.group(1)))
        else:
            other_checks.append((t, n, clause))

    indexed_cols = {(r[0], r[4]) for r in stats}

    tcols = defaultdict(list)
    for t, c, ct, dt, nullable, default, extra, genexpr, coll in cols:
        tcols[t].append(dict(name=c, ctype=ct.lower(), dtype=dt.lower(), nullable=nullable == 'YES',
                             default=None if default in ('<<NULL>>', 'NULL') else default,
                             extra=extra.lower(), gen=genexpr, coll=coll))
    colinfo = {(t, c['name']): c for t in tcols for c in tcols[t]}

    # LONGTEXT columns that hold PHP serialize() output. It contains NUL bytes, which PostgreSQL text can not store.
    SERIALIZED_TEXT_COLS = {('product', 'cheapest_price')}

    def pg_type(t, c):
        ct, dt = c['ctype'], c['dtype']
        unsigned = 'unsigned' in ct
        if ct == 'binary(16)':
            return 'uuid'
        if ct.startswith('tinyint(1)'):
            return 'boolean'
        if dt == 'tinyint' or dt == 'smallint':
            return 'smallint'
        if dt in ('int', 'mediumint'):
            return 'bigint' if unsigned else 'integer'
        if dt == 'bigint':
            return 'bigint'
        if dt in ('varchar', 'char'):
            m = re.match(r'(var)?char\((\d+)\)', ct)
            return '%s(%s)' % ('varchar' if m.group(1) else 'char', m.group(2))
        if (t, c['name']) in SERIALIZED_TEXT_COLS:
            return 'bytea'
        if dt in ('text', 'mediumtext', 'longtext', 'tinytext'):
            return 'jsonb' if (t, c['name']) in json_cols else 'text'
        if dt in ('longblob', 'mediumblob', 'blob', 'tinyblob', 'varbinary', 'binary'):
            return 'bytea'
        if dt in ('datetime', 'timestamp'):
            m = re.search(r'\((\d)\)', ct)
            return 'timestamp(%s)' % (m.group(1) if m else '0')
        if dt == 'date':
            return 'date'
        if dt == 'double':
            return 'double precision'
        if dt == 'float':
            return 'real'
        if dt == 'decimal':
            m = re.search(r'\((\d+),(\d+)\)', ct)
            return 'numeric(%s,%s)' % m.groups()
        raise ValueError('unmapped type %s for %s.%s' % (ct, t, c['name']))

    def pg_default(t, c, ptype):
        d = c['default']
        if d is None:
            return None
        if ptype == 'uuid':
            if not c['name'].endswith('version_id'):
                warnings.append('binary(16) default on non-version column %s.%s skipped' % (t, c['name']))
                return None
            return "'%s'" % LIVE_VERSION_UUID  # verified against Defaults::LIVE_VERSION, raw bytes are mangled by information_schema
        if d.lower() == 'current_timestamp()' or d.lower().startswith('current_timestamp('):
            return 'CURRENT_TIMESTAMP'
        if d.lower() == 'json_object()':
            return "'{}'::jsonb"
        if d.lower() == 'json_array()':
            return "'[]'::jsonb"
        if ptype == 'boolean':
            return 'true' if d in ('1', "b'1'") else 'false'
        s = mysql_unquote(d)
        if s is not None:
            return lit(s)
        if re.fullmatch(r'-?\d+(\.\d+)?', d):
            return d
        warnings.append('unhandled default %r on %s.%s' % (d, t, c['name']))
        return None

    def gen_expr(t, c, ptype):
        e = c['gen']
        m = re.fullmatch(r"json_unquote\(json_extract\(`(\w+)`,'\$\.(\w+)'\)\)", e)
        if m:
            base = '(%s->>%s)' % (q(m.group(1)), lit(m.group(2)))
            cast = {'double precision': '::double precision', 'integer': '::integer'}.get(ptype, '')
            return base + cast
        m = re.fullmatch(r'cast\(`(\w+)` as date\)', e)
        if m:
            return 'CAST(%s AS date)' % q(m.group(1))
        m = re.fullmatch(r'reverse\(`(\w+)`\)', e)
        if m:
            return 'reverse(%s)' % q(m.group(1))
        m = re.fullmatch(r'if\(`(\w+)` = 1,`(\w+)`,NULL\)', e)
        if m:
            return 'CASE WHEN %s THEN %s END' % (q(m.group(1)), q(m.group(2)))
        raise ValueError('unhandled generation expression %s.%s: %s' % (t, c['name'], e))

    out = []
    emit = out.append
    emit('-- Generated by mysql-to-pg-ddl.py from %s/%s. Do not edit by hand.' % (args.container, args.db))
    emit('CREATE SCHEMA IF NOT EXISTS %s;' % q(args.schema))
    emit('SET search_path TO %s;' % q(args.schema))
    emit("CREATE COLLATION IF NOT EXISTS ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);")

    stat_by_table = defaultdict(lambda: defaultdict(list))
    unique_flag = {}
    for t, idx, nonuniq, seq, col, sub in stats:
        stat_by_table[t][idx].append(col)
        unique_flag[(t, idx)] = nonuniq == '0'

    trig = []
    for t in tables:
        lines = []
        for c in tcols[t]:
            ptype = pg_type(t, c)
            parts = [q(c['name']), ptype]
            if c['coll'] == 'utf8mb4_unicode_ci' and ptype.split('(')[0] in ('varchar', 'char', 'text') and args.ci == 'all':
                parts.append('COLLATE "ci"')
            if 'generated' in c['extra']:
                stored = 'stored' in c['extra'] or 'persistent' in c['extra'] or (t, c['name']) in indexed_cols
                parts.append('GENERATED ALWAYS AS (%s) %s' % (gen_expr(t, c, ptype), 'STORED' if stored else 'VIRTUAL'))
            else:
                if 'auto_increment' in c['extra']:
                    parts.append('GENERATED BY DEFAULT AS IDENTITY')
                else:
                    d = pg_default(t, c, ptype)
                    if d is not None:
                        parts.append('DEFAULT ' + d)
                if not c['nullable']:
                    parts.append('NOT NULL')
            if 'on update' in c['extra']:
                trig.append((t, c['name']))
            lines.append('    ' + ' '.join(parts))
        pk = stat_by_table[t].get('PRIMARY')
        if pk:
            lines.append('    PRIMARY KEY (%s)' % ', '.join(q(x) for x in pk))
        for tt, n, clause in other_checks:
            if tt == t:
                expr = clause.replace('`', '"')
                lines.append('    CONSTRAINT %s CHECK (%s)' % (q(n), expr))
        emit('CREATE TABLE %s (\n%s\n);' % (q(t), ',\n'.join(lines)))

    def shorten(name):
        if len(name.encode()) <= 63:
            return name
        h = hashlib.md5(name.encode()).hexdigest()[:8]
        return name[:54] + '_' + h

    truncated = 0
    for t in tables:
        for idx, icols in stat_by_table[t].items():
            if idx == 'PRIMARY':
                continue
            name = '%s.%s' % (t, idx)
            if len(name.encode()) > 63:
                truncated += 1
            emit('CREATE %sINDEX %s ON %s (%s);' % ('UNIQUE ' if unique_flag[(t, idx)] else '', q(shorten(name)), q(t),
                                                   ', '.join(q(x) for x in icols)))

    fks = defaultdict(lambda: dict(cols=[], rcols=[]))
    for t, n, c, rt, rc, dr, ur in fkcols:
        f = fks[(t, n)]
        f.update(rt=rt, dr=dr, ur=ur)
        f['cols'].append(c)
        f['rcols'].append(rc)
    for (t, n), f in sorted(fks.items()):
        emit('ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s ON UPDATE %s;' % (
            q(t), q(n), ', '.join(q(x) for x in f['cols']), q(f['rt']), ', '.join(q(x) for x in f['rcols']),
            f['dr'], f['ur']))

    if trig:
        emit('CREATE FUNCTION set_updated_at_now() RETURNS trigger LANGUAGE plpgsql AS $$\n'
             'BEGIN NEW.updated_at := CURRENT_TIMESTAMP; RETURN NEW; END $$;')
        for t, c in trig:
            if c != 'updated_at':
                warnings.append('ON UPDATE trigger function is hard-wired to updated_at, got %s.%s' % (t, c))
            emit('CREATE TRIGGER %s BEFORE UPDATE ON %s FOR EACH ROW EXECUTE FUNCTION set_updated_at_now();' % (
                q('trg_%s_%s_on_update' % (t, c)), q(t)))

    sys.stdout.write('\n'.join(out) + '\n')
    sys.stderr.write('tables=%d columns=%d indexes(non-PK)=%d fks=%d on-update-triggers=%d index-names-truncated=%d dropped-json-checks=%d kept-checks=%d\n' % (
        len(tables), len(colinfo), sum(1 for t in tables for i in stat_by_table[t] if i != 'PRIMARY'), len(fks), len(trig), truncated,
        len(json_cols), len(other_checks)))
    for w in warnings:
        sys.stderr.write('WARNING: ' + w + '\n')


if __name__ == '__main__':
    main()
